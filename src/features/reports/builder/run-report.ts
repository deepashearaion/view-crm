import type { QueryClient } from '@tanstack/react-query';

import type { Access, User } from '@/features/auth';
import { formatDateTime } from '@/lib/format';
import { downloadXlsx, xlsxFileName, type CellValue, type Sheet } from '@/lib/xlsx';

import { formatReportRange } from '../report-range';
import type { ReportRange } from '../types';

import {
  ALL_VALUES,
  ANY_DATE,
  loadContacts,
  REPORT_DATASETS,
  type ReportColumn,
  type ReportDataset,
  type ReportLookups,
  type ReportRequest,
} from './datasets';

export interface GeneratedReport {
  dataset: ReportDataset;
  request: ReportRequest;
  columns: ReportColumn[];
  rows: CellValue[][];
  generatedAt: Date;
}

/** Names for owner and contact columns. Contacts load only when a contact column is picked. */
async function buildLookups(
  queryClient: QueryClient,
  dataset: ReportDataset,
  columnIds: readonly string[],
  users: Map<string, User>,
  access: Access,
): Promise<ReportLookups> {
  const contacts = new Map<string, string>();
  if (dataset.usesContacts(columnIds) && access.can('contacts', 'view')) {
    for (const contact of await loadContacts(queryClient)) {
      contacts.set(contact.id, contact.fullName);
    }
  }
  return {
    userName: (id) => (id ? (users.get(id)?.name ?? `User #${id}`) : ''),
    contactName: (id) => (id ? (contacts.get(id) ?? `Contact #${id}`) : ''),
  };
}

export async function generateReport(
  queryClient: QueryClient,
  dataset: ReportDataset,
  request: ReportRequest,
  users: Map<string, User>,
  access: Access,
): Promise<GeneratedReport> {
  const lookups = await buildLookups(queryClient, dataset, request.columnIds, users, access);
  const rows = await dataset.run(queryClient, request, lookups);
  const columns = request.columnIds
    .map((id) => dataset.columns.find((column) => column.id === id))
    .filter((column) => column !== undefined);
  return { dataset, request, columns, rows, generatedAt: new Date() };
}

/** Plain-language description of the period and filter a report was built with. */
export function describeReport(report: Pick<GeneratedReport, 'dataset' | 'request'>): {
  period: string;
  filter: string;
} {
  const { dataset, request } = report;
  const range = formatReportRange(request.range);
  let period: string;
  if (dataset.period === 'none') period = 'Current snapshot (not tied to a period)';
  else if (dataset.period === 'api') period = range;
  else if (request.dateBasis === ANY_DATE) period = 'Any date';
  else {
    const basis = dataset.dateBases.find((item) => item.id === request.dateBasis);
    period = `${basis?.label ?? 'Date'}: ${range}`;
  }
  const option = dataset.filter?.options.find((item) => item.value === request.filter);
  const filter =
    dataset.filter && request.filter !== ALL_VALUES && option
      ? `${dataset.filter.label}: ${option.label}`
      : '';
  return { period, filter };
}

function reportSheet(report: GeneratedReport): Sheet {
  return {
    name: report.dataset.label,
    columns: report.columns.map((column) => ({ header: column.label, format: column.format })),
    rows: report.rows,
  };
}

function detailsSheet(entries: [string, string][]): Sheet {
  return {
    name: 'About this report',
    columns: [{ header: 'Detail' }, { header: 'Value' }],
    rows: entries,
  };
}

/** Saves a generated report as .xlsx: the data sheet plus an "About this report" sheet. */
export function downloadReport(report: GeneratedReport, generatedBy: string): void {
  const { period, filter } = describeReport(report);
  const about: [string, string][] = [
    ['Report', report.dataset.label],
    ['Period', period],
  ];
  if (filter) about.push(['Filter', filter]);
  about.push(
    ['Rows', String(report.rows.length)],
    ['Generated', formatDateTime(report.generatedAt)],
  );
  if (generatedBy) about.push(['Generated by', generatedBy]);

  const range =
    report.dataset.period === 'none' ? [] : [report.request.range.from, report.request.range.to];
  downloadXlsx(xlsxFileName('climetavere', report.dataset.label, ...range), [
    reportSheet(report),
    detailsSheet(about),
  ]);
}

/**
 * The whole Reports overview as one workbook: a sheet per summary report the user can see,
 * every column, for the selected period.
 */
export async function downloadOverview(
  queryClient: QueryClient,
  range: ReportRange,
  users: Map<string, User>,
  access: Access,
  generatedBy: string,
): Promise<void> {
  const datasets = REPORT_DATASETS.filter(
    (dataset) => dataset.group === 'summary' && dataset.allowed(access),
  );
  const reports = await Promise.all(
    datasets.map((dataset) =>
      generateReport(
        queryClient,
        dataset,
        {
          range,
          dateBasis: ANY_DATE,
          filter: ALL_VALUES,
          columnIds: dataset.columns.map((column) => column.id),
        },
        users,
        access,
      ),
    ),
  );
  const about: [string, string][] = [
    ['Report', 'Reports overview'],
    ['Period', formatReportRange(range)],
    [
      'Note',
      'Open pipeline is a snapshot of right now; revenue covers at most the last 36 months.',
    ],
    ['Generated', formatDateTime(new Date())],
  ];
  if (generatedBy) about.push(['Generated by', generatedBy]);
  downloadXlsx(xlsxFileName('climetavere', 'reports', range.from, range.to), [
    ...reports.map(reportSheet),
    detailsSheet(about),
  ]);
}
