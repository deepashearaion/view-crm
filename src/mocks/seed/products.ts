export function seedProducts(now: number = Date.now()): ProductDto[] {
  return legacyCatalog.map(([name, description, unit, salePrice, discount, taxPercent], index) => {
    const created = new Date(now - (legacyCatalog.length - index) * 86_400_000).toISOString();
    return {
      id: 500 + index,
      name,
      description,
      type: 'product',
      category: 'Travel package',
      sku: `PKG-${String(500 + index)}`,
      unit,
      purchase_price: null,
      sale_price: salePrice,
      discount_type: 'amount',
      discount,
      tax_percent: taxPercent,
      stock: null,
      created_at: created,
      updated_at: created,
    };
  });
}
